export type Copy = (typeof copy)[Locale];

export function label(value: string, locale: Locale) {
  return names[value]?.[locale === 'zh-CN' ? 'zh' : 'en'] ?? value.replaceAll('_', ' ');
}

export function roleLabel(role: string, locale: Locale) {
  return roleNames[role]?.[locale === 'zh-CN' ? 'zh' : 'en'] ?? role;
}

/** Replaces every `{token}` in a copy string with the matching value. */
export function fill(text: string, values: Record<string, string | number>) {
  return Object.entries(values).reduce(
    (result, [token, value]) => result.replaceAll(`{${token}}`, String(value)),
    text,
  );
}
