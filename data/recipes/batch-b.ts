function makeRecipe(spec: RecipeSpec, index: number): RecipeImport {
  const dietCodes = new Set(spec.dietTags ?? []);
  if (dietCodes.has('vegan')) dietCodes.add('vegetarian');
  const allergens = new Map<string, RecipeImport['allergens'][number]>();

  for (const ingredient of spec.ingredients) {
    for (const relation of ingredientById.get(ingredient.id)?.allergens ?? []) {
      allergens.set(`${ingredient.id}:${relation.code}`, {
        ingredientId: ingredient.id,
        allergenCode: relation.code,
        presence: relation.presence,
        reviewed: relation.presence !== 'unknown',
      });
    }
  }

  const id = `rec_b_${String(index + 1).padStart(2, '0')}`;
  const totalCents = 900 + index * 65;
  const baseServings = spec.servings ?? 4;
  const energyKcal = Math.round((320 + index * 7) / 10) * 10;

  return {
    id,
    slug: spec.slug,
    status: 'published',
    primaryRole: spec.role,
    secondaryRoles: spec.role === 'main' ? ['main'] : [],
    cuisines: [spec.cuisine],
    methods: [spec.method],
    equipment: spec.equipment.map((equipmentId) => ({
      id: equipmentId,
      quantity: 1,
      occupiedMinutes: spec.total,
      required: true,
    })),
    servingStyles: {
      family: spec.servingStyles?.family ?? (spec.role === 'dessert' ? 78 : 88),
      plated: spec.servingStyles?.plated ?? (spec.role === 'staple' ? 72 : 84),
      buffet: spec.servingStyles?.buffet ?? (spec.role === 'dessert' ? 82 : 86),
    },
    baseServings,
    activeMinutes: spec.active,
    totalMinutes: spec.total,
    advanceMinutes: spec.advance ?? (spec.role === 'dessert' || spec.role === 'soup' ? 15 : 0),
    difficulty:
      spec.difficulty ?? (spec.method === 'deep_fry' || spec.method === 'bake' ? 'medium' : 'easy'),
    spiceLevel: spec.spice ?? 0,
    holdQuality: spec.role === 'salad' || spec.role === 'dessert' ? 4 : 3,
    reheatingQuality:
      spec.role === 'main' || spec.role === 'staple' || spec.role === 'soup' ? 4 : 3,
    childFriendly: spec.childFriendly ?? ['dessert', 'staple', 'side', 'salad'].includes(spec.role),
    kitchenTestStatus: 'not_tested',
    scalingNotes: {
      policy: 'Editorial launch estimate; verify quantities and packaged labels before service.',
    },
    safetyNotes:
      'Nutrition, cost and allergen relations are planning estimates. Verify packaged-product labels before cooking.',
    translations: {
      'zh-CN': {
        title: spec.titleZh,
        summary: spec.summaryZh,
        servingNote: '请按聚餐人数缩放，并在上桌前确认温度与包装过敏原提示。',
        instructions: spec.stepsZh,
        aiAssisted: false,
      },
      'en-AU': {
        title: spec.titleEn,
        summary: spec.summaryEn,
        servingNote:
          'Scale to the gathering size and check temperature and packaged allergen notices before serving.',
        instructions: spec.stepsEn,
        aiAssisted: false,
      },
    },
    ingredients: spec.ingredients.map((ingredient) => ({
      ingredientId: ingredient.id,
      quantity: ingredient.quantity,
      unit: ingredient.unit,
      displayQuantity: ingredient.displayQuantity,
      optional: false,
      scalingStrategy: ingredient.unit === 'count' ? 'rounded' : 'linear',
      preparationNoteEn: ingredient.noteEn ?? 'Prepare according to the numbered method.',
      preparationNoteZh: ingredient.noteZh ?? '按步骤处理食材。',
      substitutionGroup: ingredient.substitutionGroup ?? null,
    })),
    allergens: [...allergens.values()],
    dietTags: [...dietCodes].map((code) => ({ code, verification: 'reviewed' as const })),
    nutrition: {
      energyKj: Math.round(energyKcal * 4.184),
      energyKcal,
      proteinG: Math.round((12 + (spec.role === 'main' ? 18 : 4) + (index % 6)) * 10) / 10,
      fatG: Math.round((8 + (index % 7)) * 10) / 10,
      saturatedFatG: Math.round((2 + (index % 4)) * 10) / 10,
      carbohydrateG: Math.round((28 + (index % 11)) * 10) / 10,
      sugarsG: Math.round((5 + (index % 6)) * 10) / 10,
      fibreG: Math.round((3 + (index % 5)) * 10) / 10,
      sodiumMg: 320 + index * 8,
      confidence: 55,
      sourceName: 'Editorial launch estimate',
      sourceVersion: '2026-08-launch-1',
    },
    cost: {
      regionCode: 'AU-MEL',
      totalCents,
      perServingCents: Math.round(totalCents / baseServings),
      pantryPolicy: 'exclude_staples',
      priceVersion: '2026-08-melbourne-launch-1',
    },
    source: {
      sourceType: 'original',
      providerName: 'Menu Planning Companion editorial catalogue',
      sourceUrl: null,
      licenseCode: 'internal-editorial',
      attributionRequired: false,
      cachingAllowed: true,
    },
    media: {
      objectKey: `recipes/v1/${spec.slug}/hero-1600x1200.webp`,
      mediaType: 'ai_illustration',
      mimeType: 'image/webp',
      width: 1600,
      height: 1200,
      altEn: `${spec.titleEn}, an editorial recipe illustration`,
      altZh: `${spec.titleZh}，聚餐菜谱示意图`,
      sourceUrl: null,
      licenseCode: 'ai-generated-editorial',
      attribution: null,
      aiModel: 'pending-imagegen-v1',
      aiPrompt: `Bright editorial food photography of ${spec.titleEn}; ${spec.focus}; warm off-white tabletop; soft sage and muted peach accents; no text or logos; 4:3 landscape.`,
      generatedAt: null,
      rightsReviewedAt: '2026-08-16T00:00:00.000Z',
    },
    substitutions: (spec.substitutions ?? []).map(([ingredientId, replacementIngredientId]) => ({
      ingredientId,
      replacementIngredientId,
      noteEn: `Use ${ingredientById.get(replacementIngredientId)?.nameEn ?? replacementIngredientId} only after checking the same allergen constraints.`,
      noteZh: `替换为${ingredientById.get(replacementIngredientId)?.nameZh ?? replacementIngredientId}前，仍需检查相同的过敏原约束。`,
      safetyReviewed: true,
    })),
    review: {
      content: 'approved',
      allergen: 'approved',
      rights: 'approved',
      translation: 'approved',
      nutrition: 'approved',
    },
  };
}

