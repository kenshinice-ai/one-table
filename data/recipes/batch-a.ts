type RecipeSpec = {
  slug: string;
  titleZh: string;
  titleEn: string;
  role: RecipeImport['primaryRole'];
  cuisine: string;
  method: string;
  equipment: string[];
  focus: string;
  ingredients: Array<[string, number, 'g' | 'ml' | 'count', string, string?]>;
  dietTags?: string[];
  active: number;
  total: number;
  advance?: number;
  difficulty?: RecipeImport['difficulty'];
  spice?: number;
  childFriendly?: boolean;
  servings?: number;
  servingStyles?: Partial<Record<'family' | 'plated' | 'buffet', number>>;
  substitutions?: Array<[string, string]>;
  status?: RecipeImport['status'];
};

const ingredientById = new Map(ingredientCatalog.map((ingredient) => [ingredient.id, ingredient]));

function makeIngredients(spec: RecipeSpec): RecipeImport['ingredients'] {
  return spec.ingredients.map(
    ([ingredientId, amount, unit, displayQuantity, substitutionGroup]) => ({
      ingredientId,
      quantity: amount,
      unit,
      displayQuantity,
      optional: false,
      scalingStrategy: unit === 'count' ? 'rounded' : 'linear',
      preparationNoteEn: '',
      preparationNoteZh: '',
      substitutionGroup: substitutionGroup ?? null,
    }),
  );
}

function makeAllergens(spec: RecipeSpec): RecipeImport['allergens'] {
  const relations = new Map<string, RecipeImport['allergens'][number]>();
  for (const [ingredientId] of spec.ingredients) {
    for (const allergen of ingredientById.get(ingredientId)?.allergens ?? []) {
      relations.set(`${ingredientId}:${allergen.code}`, {
        ingredientId,
        allergenCode: allergen.code,
        presence: allergen.presence,
        reviewed: allergen.presence !== 'unknown',
      });
    }
  }
  if (spec.slug === 'thai-green-curry-tofu') {
    relations.set('curry_paste:soy', {
      ingredientId: 'curry_paste',
      allergenCode: 'soy',
      presence: 'unknown',
      reviewed: false,
    });
  }
  return [...relations.values()];
}

